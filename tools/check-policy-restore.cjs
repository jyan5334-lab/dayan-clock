const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { migrateLegacyBackups, hasBackups, matchesRestoredPolicies } = require('../desktop/policy-backups.cjs');

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'dayan-policy-restore-'));
const appData = path.join(root, 'appdata');
const current = path.join(appData, 'DAYAN桌面');
const legacy = path.join(appData, 'DAYAN时钟');
const name = 'windows-lockdown-backup.json';
fs.mkdirSync(legacy, { recursive: true });
const backup = { original: true };
fs.writeFileSync(path.join(legacy, name), '\uFEFF' + JSON.stringify(backup));
assert.equal(hasBackups(current), false);
assert.deepEqual(migrateLegacyBackups(current, appData), [name]);
assert.equal(hasBackups(current), true);
assert.deepEqual(migrateLegacyBackups(current, appData), []);
fs.unlinkSync(path.join(current, name));
assert.deepEqual(migrateLegacyBackups(current, appData), [], 'A consumed backup must never be reimported');
assert.equal(hasBackups(current), false);
fs.writeFileSync(path.join(current, name), JSON.stringify({ newAuthorization: true }));
migrateLegacyBackups(current, appData);
assert.deepEqual(JSON.parse(fs.readFileSync(path.join(current, name))), { newAuthorization: true });
assert.ok(fs.existsSync(path.join(legacy, name)), 'Keep the old source available for manual recovery');
const isolated = path.join(root, 'isolated');
assert.deepEqual(migrateLegacyBackups(isolated, null), [], 'Tests must not import the real profile');

const policies = ['DisableTaskMgr', 'DisableLockWorkstation', 'DisableChangePassword', 'NoWinKeys', 'NoLogoff'];
const record = { at: new Date().toISOString(), policies: policies.map(Name => ({ Name, Exists: false, Value: null })) };
const status = { policies: policies.map(name => ({ name, exists: false, value: null })), error: '' };
assert.equal(matchesRestoredPolicies(status, record), true);
assert.equal(matchesRestoredPolicies({ ...status, error: 'Access denied' }, record), false);
assert.equal(matchesRestoredPolicies(status, { ...record, policies: record.policies.slice(1) }), false);
assert.equal(matchesRestoredPolicies(status, { ...record, policies: record.policies.map(() => record.policies[0]) }), false);
assert.equal(matchesRestoredPolicies({ ...status, policies: status.policies.map(p => ({ ...p, exists: true, value: 1 })) }, record), false);
const originalRestriction = structuredClone(record);
originalRestriction.policies[0] = { Name: policies[0], Exists: true, Value: 1 };
const originalStatus = structuredClone(status);
originalStatus.policies[0] = { name: policies[0], exists: true, value: 1 };
assert.equal(matchesRestoredPolicies(originalStatus, originalRestriction), true, 'Preserve restrictions that existed before DAYAN');
const filter = { stage: 'restored', secureKeys: [{ Id: 'Ctrl+Alt+Del', Enabled: false }], settings: [{ Name: 'DisableKeyboardFilterForAdministrators', Value: 'true' }] };
assert.equal(matchesRestoredPolicies({ ...status, keyboardFilterEnabled: false, administratorFiltering: false }, { ...record, filter }), true);
assert.equal(matchesRestoredPolicies({ ...status, keyboardFilterEnabled: true, administratorFiltering: false }, { ...record, filter }), false);
assert.equal(matchesRestoredPolicies({ ...status, keyboardFilterEnabled: false, administratorFiltering: true }, { ...record, filter }), false);

if (process.platform !== 'win32') throw Error('PowerShell behavior tests require Windows');
const powershell = path.join(process.env.SystemRoot, 'System32/WindowsPowerShell/v1.0/powershell.exe');
const result = spawnSync(powershell, ['-NoLogo', '-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', path.join(__dirname, 'check-policy-restore.ps1'), '-TestDirectory', root], { encoding: 'utf8', windowsHide: true, timeout: 60000 });
assert.equal(result.status, 0, result.stderr || result.stdout);
console.log(JSON.stringify({ migration: 'passed', readback: 'passed', powershell: JSON.parse(result.stdout.trim().split(/\r?\n/).at(-1)), result: 'passed' }, null, 2));
